import { isAuthSessionMissingError } from '@supabase/supabase-js';

/**
 * ============================================================
 * ★★ "쇼핑몰 회원으로 인정하는가" — 이 사이트의 단 하나뿐인 정의
 * ============================================================
 *
 * ★★ 왜 만들었는가 (2026-08-25)
 *   같은 규칙이 세 곳에 따로 적혀 있었고, 그중 한 곳이 달랐습니다.
 *
 *     헤더(api/auth/me)   로그인 + 프로필 있음 + 탈퇴 아님
 *     마이페이지(lib/auth) 로그인 + 프로필 있음 + 탈퇴 아님
 *     미들웨어             로그인만  ← 여기만 달랐습니다
 *
 *   그래서 프로필을 못 읽는 순간 손님 화면이 서로 다른 말을 했습니다.
 *     · 헤더는 "로그인 / 회원가입" 을 보여 주고
 *     · 그 로그인을 누르면 미들웨어가 마이페이지로 돌려보내고
 *     · 마이페이지는 "이 계정으로는 쓸 수 없습니다" 를 띄웠습니다
 *   손님은 로그인이 된 건지 아닌지 알 수 없었습니다.
 *
 *   이제 규칙은 여기 한 곳에만 있습니다. 바꿀 일이 생기면 여기만 고치세요.
 *
 * ★ Edge(미들웨어)와 Node(서버 화면) 양쪽에서 씁니다.
 *   그래서 server-only · next/headers · service_role 을 쓰지 않습니다.
 *   여기에 그런 것을 들여오면 미들웨어가 빌드되지 않습니다.
 */

/**
 * 쇼핑몰 회원으로 인정할 수 있는 프로필인가.
 *
 * @param profile 프로필 행. 없으면 null 을 넘기세요.
 */
export function isActiveMember<T extends { status: string }>(
  profile: T | null | undefined
): profile is T {
  if (!profile) return false;

  /*
   * ★★ 'inactive' 는 지금도 회원으로 인정합니다. 일부러 그렇게 둡니다.
   *
   *   막는 자리는 여기가 아니라 로그인하는 순간입니다.
   *     app/(shop)/auth-actions.ts  — loginAction 이 inactive 를 되돌려보냅니다
   *     app/auth/callback/route.ts  — 소셜 로그인도 같습니다
   *   두 곳 모두 signOut 까지 시켜 세션을 지웁니다. 즉 정지된 계정은
   *   애초에 세션을 갖지 못합니다.
   *
   *   그런데도 여기서까지 막으면, 이미 로그인해 있던 손님을 이용 중에
   *   갑자기 잘라내게 됩니다. 그 손님은 마이페이지에서 "이 계정으로는
   *   쓸 수 없습니다" 를 보게 되고, 왜 그런지는 아무 데도 안 나옵니다.
   *   정지는 관리자가 사람을 보고 내리는 조치이므로, 다음 로그인 때
   *   분명한 안내와 함께 막는 편이 낫습니다.
   *
   *   ★ 'withdrawn'(탈퇴)만 여기서 막습니다. 되돌릴 일이 없는 상태이고,
   *     본인이 스스로 누른 것이라 이유를 이미 압니다.
   */
  return profile.status !== 'withdrawn';
}

/**
 * "그냥 로그인을 안 한 것" 인가.
 *
 * ★★ 이걸 왜 가리는가 — 로그를 남기고 말고를 여기서 정합니다.
 *   Supabase 는 로그인하지 않은 사람에게도 error 를 돌려줍니다.
 *   (AuthSessionMissingError) 그것까지 로그로 찍으면 손님이 상품 페이지를
 *   한 장 열 때마다 쌓입니다. 정작 진짜 문제가 그 속에 묻힙니다.
 *   그래서 이것만 조용히 넘기고, 나머지 오류는 전부 남깁니다.
 *
 * ★ 라이브러리가 주는 판별 함수를 그대로 씁니다.
 *   status(400) 로도 걸러 볼까 했지만, 400 은 다른 오류도 함께 걸립니다.
 *   이름으로만 보는 것이 정확하고, 라이브러리가 바뀌어도 따라갑니다.
 */
export function isJustLoggedOut(error: unknown): boolean {
  return isAuthSessionMissingError(error);
}
