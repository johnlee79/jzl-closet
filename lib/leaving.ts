'use client';

/**
 * ============================================================
 * ★★ "우리가 일부러 다른 사이트로 떠나는 중" 표시 (2026-08-25)
 * ============================================================
 *
 * ★★ 무엇을 위한 것인가
 *   구글·카카오 로그인은 우리 화면을 떠나 그쪽 동의 화면으로 넘어갑니다.
 *   그 순간 브라우저는 진행 중이던 요청을 끊습니다.
 *
 *   문제는 브라우저마다 그것을 다르게 다룬다는 점입니다.
 *     크롬  — 조용히 버립니다
 *     사파리 — 오류로 던집니다 (TypeError: Load failed)
 *   그래서 아이폰에서만 "Application error" 화면이 잠깐 보였습니다.
 *   (아이폰은 크롬을 써도 속은 사파리 엔진입니다)
 *
 *   떠나면서 끊긴 것은 고장이 아닙니다. 손님에게 오류 화면을 보일 일이
 *   아닙니다. 이 표시가 그 둘을 갈라 줍니다.
 *
 * ★★ 스스로 부른 경우에만 참입니다.
 *   markLeaving() 을 우리가 직접 부른 뒤에만 켜집니다.
 *   그냥 링크를 누르거나 뒤로 가는 것으로는 켜지지 않습니다.
 *   진짜 고장은 그대로 전부 보여 줘야 하기 때문입니다.
 *
 * ★★ 잠깐만 켜 둡니다.
 *   이동이 취소될 수 있습니다. 손님이 곧바로 뒤로 가거나, 그쪽 사이트가
 *   안 열려 우리 화면에 그대로 남는 경우입니다. 그때까지 표시를 켜 두면
 *   그 뒤에 나는 진짜 고장까지 감춰 버립니다.
 *   그래서 짧게 켰다가 스스로 꺼집니다.
 */

/** 표시를 켜 두는 시간. 이 안에 화면이 안 바뀌면 이동이 무산된 것으로 봅니다. */
const WINDOW_MS = 10_000;

let leavingUntil = 0;

/**
 * 다른 사이트로 떠나기 직전에 부릅니다.
 * ★ window.location.assign() 바로 앞에 두세요. 뒤에 두면 늦습니다.
 */
export function markLeaving(): void {
  leavingUntil = Date.now() + WINDOW_MS;
}

/** 지금 우리가 일부러 떠나는 중인가. */
export function isLeaving(): boolean {
  return Date.now() < leavingUntil;
}

/** 이동이 무산된 것을 알았을 때 즉시 표시를 끕니다. */
export function clearLeaving(): void {
  leavingUntil = 0;
}
