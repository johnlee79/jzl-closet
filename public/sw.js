/*
 * ============================================================
 * 서비스 워커 — 아무것도 저장하지 않습니다
 * ============================================================
 *
 * ★★ 왜 있는가
 *   안드로이드 크롬은 "홈 화면에 추가" 를 권할 때 서비스 워커가 등록되어
 *   있고 fetch 를 다루는지를 봅니다. 없으면 설치 안내(beforeinstallprompt)가
 *   아예 뜨지 않습니다. 그래서 최소한의 것만 둡니다.
 *
 * ★★ 왜 캐시를 안 하는가 — 이게 중요합니다
 *   흔히 서비스 워커로 화면을 저장해 두고 빨리 보여 주지만, 쇼핑몰에서는
 *   그게 사고가 됩니다.
 *     · 품절된 상품이 계속 판매중으로 보입니다
 *     · 가격을 내렸는데 옛 가격이 보입니다
 *     · 주문 완료 화면 같은 개인 정보가 남습니다
 *   그래서 이 워커는 요청에 손대지 않고 그대로 통과시킵니다.
 *   "설치할 수 있는 사이트" 로 만들어 주는 역할만 합니다.
 *
 * ★ 나중에 캐시를 넣고 싶어지면, 반드시 상품·주문·관리자 주소를 빼고
 *   글꼴·아이콘 같은 안 바뀌는 파일만 넣으세요.
 */

self.addEventListener('install', () => {
  // 새 워커가 바로 일하도록 기다리지 않습니다.
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  /*
   * ★ 예전에 캐시를 만들어 둔 적이 있다면 전부 지웁니다.
   *   이 파일은 캐시를 안 쓰므로, 남아 있으면 옛 화면이 계속 보일 수 있습니다.
   */
  event.waitUntil(
    (async () => {
      try {
        const names = await caches.keys();
        await Promise.all(names.map((name) => caches.delete(name)));
      } catch (error) {
        /* 저장소를 못 쓰는 환경이면 그냥 넘어갑니다. */
      }
      await self.clients.claim();
    })()
  );
});

/*
 * ★ fetch 를 듣기만 하고 아무것도 하지 않습니다.
 *   respondWith 를 부르지 않으면 브라우저가 평소대로 네트워크로 갑니다.
 *   이 핸들러가 있어야 설치 조건을 만족합니다.
 */
self.addEventListener('fetch', () => {});
