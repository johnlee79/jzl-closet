-- ── 1. 원본 로고 주소 ──────────────────────────────────────
--
-- 왜 필요한가
--   균일화는 되돌릴 수 없는 처리입니다. 800×360 캔버스에 얹어 저장하는
--   순간 원래 크기 정보가 사라집니다. 나중에 기준값(목표 면적·잉크 보정)을
--   바꿔 다시 굽고 싶어도, 이미 축소된 이미지를 다시 키우면 화질이 깨집니다.
--
--   그래서 원본을 R2 의 brands/original/ 로 따로 복사해 두고 그 주소를 여기에
--   적어 둡니다. 다시 처리할 때는 언제나 이 원본에서 시작합니다.
--
-- ★ 비어 있으면 아직 한 번도 균일화하지 않은 로고입니다.
alter table public.brands
  add column if not exists logo_original_url text;

comment on column public.brands.logo_original_url is
  '균일화 전 원본 로고 주소. 기준값을 바꿔 다시 처리할 때 항상 여기서 시작합니다.';


-- ── 2. 브랜드별 미세 조정 배율 ─────────────────────────────
--
-- 왜 필요한가
--   잉크 밀도 보정을 자동으로 넣어도 눈으로 봐야 알 수 있는 차이가 남습니다.
--   그때 이미지 처리 로직을 통째로 바꾸면 다른 14개가 같이 흔들립니다.
--   그 브랜드만 1.15 같은 값을 주는 편이 안전합니다.
--
--   특히 파타고니아는 유일하게 속이 꽉 찬 로고라 자동 보정이 가장 크게
--   걸렸습니다(k=0.55, 하한). 눈으로 보고 작아 보이면 1.1~1.2 로 올리세요.
--
-- ★ 허용 범위 0.7 ~ 1.5. 그 밖의 값은 코드가 잘라 냅니다.
--   범위를 넓히면 균일화가 무너집니다. 그럴 정도면 로고 파일 자체를 바꾸세요.
alter table public.brands
  add column if not exists logo_scale numeric not null default 1.0;

comment on column public.brands.logo_scale is
  '브랜드별 로고 미세 조정 배율 (0.7~1.5, 기본 1.0). 계산식의 logoScale 자리에 들어갑니다.';


