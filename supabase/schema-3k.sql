-- 3-K : 분류(카테고리) 대표 이미지 컬럼
-- ============================================================
--
-- 왜 필요한가
--   메인 CATEGORY 섹션의 네 칸이 전부 회색 빈 상자였습니다.
--   코드가 public/images/category/{slug}.jpg 를 참조하는데 그 파일이 없어서입니다.
--   운영자가 관리자에서 직접 올릴 수 있도록 주소를 담을 자리를 만듭니다.
--
--   brands 테이블에는 image_url 이 이미 있습니다. (schema-1b)
--   categories 에만 없어서 같은 이름으로 맞춰 둡니다.
--
-- 실행 방법
--   Supabase 대시보드 > SQL Editor 에 이 파일 내용을 붙여넣고 실행하세요.
--   먼저 돌려야 하는 파일은 없습니다. (schema-1b.sql 이 이미 돌아가 있어야 합니다)
--
-- 안전성
--   if not exists 라 여러 번 실행해도 문제가 없습니다.
--   기존 행에는 null 이 들어가고, 화면은 이미지가 없는 것으로 보고 넘어갑니다.
--   이 SQL 을 아직 돌리지 않아도 사이트는 그대로 뜹니다. (코드가 없는 컬럼을 견딥니다)
-- ============================================================

alter table public.categories
  add column if not exists image_url text;

comment on column public.categories.image_url is
  '분류 대표 이미지 주소 (R2). 메인 CATEGORY 카드에 씁니다. 비어 있으면 카드가 글자만 나옵니다.';
